import sys, json
sys.path.insert(0, "src")
from pathlib import Path
from pta.core import CoreModel, physics_report, fidelity
import tidy3d as td
import numpy as np
from pta.validate_straight import evaluate, format_report

run_dir = Path("artifacts/run_core")
core = CoreModel.from_npz(run_dir / "core_smatrix.npz")
print("=== ingested core (core_smatrix.npz) ===")
print("backend:", core.backend, "| N:", core.N, "| K:", core.K, "| alpha:", core.alpha)
print("density present:", core.density is not None, "| shape:", (core.density.shape if core.density is not None else None))
print("s_matrix shape:", core.s_matrix.shape)
print()
print("physics_report:")
print(json.dumps(physics_report(core), indent=2))
print()
print("fidelity:")
print(json.dumps(fidelity(core), indent=2))
print()
drc_core = json.loads((run_dir / "drc_core.json").read_text(encoding="utf-8"))
drc_chip = json.loads((run_dir / "drc_chip.json").read_text(encoding="utf-8"))
print("=== DRC ===")
print("drc_core passes:", drc_core.get("passes"), "| stub_landing_limit_um:", drc_core.get("stub_landing_limit_um"), "| stub_landing_um:", drc_core.get("stub_landing_um"))
print("drc_chip passes:", drc_chip.get("passes"))
print()
verification = json.loads((run_dir / "verification.json").read_text(encoding="utf-8"))
print("=== verification ===")
print(json.dumps(verification, indent=2))
print()
metrics = json.loads((run_dir / "metrics.json").read_text(encoding="utf-8"))
print("=== metrics ===")
print(json.dumps(metrics, indent=2))
print()
layout = json.loads((run_dir / "layout_manifest.json").read_text(encoding="utf-8"))
print("=== layout summary ===")
print("core_backend:", layout.get("core_backend"), "| model_status:", layout.get("model_status"))
print("declared_joints:", layout.get("declared_joints"))
print("drc:", layout.get("drc"))
inp = layout.get("inputs")
print("inputs shape:", (len(inp), len(inp[0]) if inp else None))
print()
data = td.SimulationData.from_file("artifacts/tidy3d/tidy3d_validate_straight.hdf5", monitor_names=["out_0","refl_0"])
report = evaluate(data)
print("=== straight-waveguide normalization reference (wide monitor) ===")
print(format_report(report))
print("forward normalization reference =", round(float(np.mean(report.forward_power)), 4))
